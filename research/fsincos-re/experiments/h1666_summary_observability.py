#!/usr/bin/env python3
"""Prove the retained coherent-state wall for ES/B/exception pending gates.

This does not fit or install a selector. It measures what the existing
captures cannot identify, and generates a software-only discriminator table.
"""
from __future__ import annotations

import argparse
import hashlib
import itertools
import json
from collections import Counter
from pathlib import Path

from h1640_remaining_scope_freshness import save


RAW = {
    'transfer-tests/h1656/hardware-output/state-output.txt':
        '1074ffca4a37a5d217247603c3d8439ef2a19238c42612b011b0d30d0dd4d555',
    'transfer-tests/h1662/hardware-output/state-output.txt':
        '5d56fc2803d9a0b4d60ece5d79ab766c7c1e0de660e984eb1c8c69a0aaab6321',
}
MANUAL = 'tmp/pdfs/h1644-intel-sdm-089.pdf'
MANUAL_SHA = '1eb81360c636a723fb34610a1deef276e98e1fc331ac08b380114079664add20'


def digest(path):
    h = hashlib.sha256()
    with path.open('rb') as source:
        for block in iter(lambda: source.read(1 << 20), b''):
            h.update(block)
    return h.hexdigest()


def gates(u, es, busy):
    return dict(ES=es, B=busy, flags_and_masks=u, ES_or_B=es | busy,
                ES_and_flags=es & u, ES_or_flags=es | u)


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--root', required=True, type=Path)
    p.add_argument('--output-dir', required=True, type=Path)
    a = p.parse_args()
    root, out = a.root.resolve(), a.output_dir.resolve()
    assert not out.exists()
    evidence = dict(RAW, **{MANUAL: MANUAL_SHA})
    for name, sha in evidence.items():
        assert digest(root/name) == sha, name
    counts, banks = Counter(), []
    for name in RAW:
        local = Counter()
        with (root/name).open() as source:
            for line in source:
                row = dict(word.split('=', 1) for word in line.split())
                sw, cw = int(row['B_SW'], 16), int(row['B_CW'], 16)
                u = int(bool(sw & ~cw & 0x3f))
                es, busy = (sw >> 7) & 1, (sw >> 15) & 1
                index = 4*u + 2*es + busy
                observed = int(row['FAULT_AT'] == '1')
                # This check is about pending delivery at the opcode, not
                # exceptions generated by executing it and delivered at FWAIT.
                assert observed == u == es == busy
                assert int(row['A_VALID']) == 1-observed
                local[f'{index:03b}'] += 1
        counts.update(local)
        banks.append(dict(raw=name, rows=sum(local.values()), U_ES_B=dict(local)))
    assert set(counts) == {'000', '111'}
    # All Boolean gates of these three observables: two of eight truth values
    # are constrained. Each of the remaining six can be chosen independently.
    surviving = [t for t in range(256) if not t & 1 and t & 128]
    assert len(surviving) == 64 == 2**6
    table = []
    for index in range(8):
        u, es, busy = (index >> 2) & 1, (index >> 1) & 1, index & 1
        possibilities = {t >> index & 1 for t in surviving}
        assert possibilities == ({0} if index == 0 else {1} if index == 7 else {0, 1})
        table.append(dict(index=index, U=u, ES=es, B=busy,
                          retained_rows=counts[f'{index:03b}'],
                          named_hypotheses=gates(u, es, busy),
                          unconstrained_possible_values=sorted(possibilities)))
    names = list(gates(0, 0, 0))
    separating = []
    for size in range(1, 7):
        for subset in itertools.combinations(range(1, 7), size):
            signatures = {tuple(table[i]['named_hypotheses'][name] for i in subset) for name in names}
            if len(signatures) == len(names):
                separating.append(list(subset))
        if separating:
            break
    assert separating
    # Minimality is only for these six named gates. Restricting to them would
    # be a new assumption; full Boolean identification needs all six missing
    # states. Restoration can itself collapse requested states, so a future
    # harness must save both the requested image and the actually restored SW.
    out.mkdir(parents=True)
    save(out/'discriminators.json', table)
    report = dict(experiment='h1666_summary_observability',
        status='PROVED_COHERENT_STATE_OBSERVABILITY_LIMIT', actual_rows=sum(counts.values()),
        banks=banks, U_ES_B_counts=dict(counts), consistent_three_input_Boolean_gates=len(surviving),
        named_gate_count=len(names), minimum_named_discriminator_states=len(separating[0]),
        all_minimum_named_discriminator_sets=separating,
        all_unrestricted_gate_discriminator_states=list(range(1, 7)),
        fresh_hardware_labels=0, hardware_execution='none', manifest_frozen=False,
        private_ledger_access='none', production_default_or_paper_changed=False,
        manual=dict(url='https://cdrdv2-public.intel.com/868137/325462-089-sdm-vol-1-2abcd-3abcd-4.pdf',
            section='Vol. 1, 8.6', interpretation='Describes ES as the pending check. Does not by itself prove which inconsistent states survive FXRSTOR or their silicon behavior.'),
        next_observation_requirement='First verify requested-versus-restored SW, CW, raw ST0 and tags; distinguish restore canonicalization from waiting-instruction consumption. Use only fresh audited operands and one instruction attempt. Do not credit discarded/canonicalized states as if they were executed.',
        claim_boundary='Exact finite identifiability theorem for Boolean functions of U, ES and B under the observed diagonal support. It neither proves the physical gate has only those inputs nor chooses a winning selector.',
        sha256=dict(script=digest(Path(__file__)), evidence=evidence,
                    discriminators=digest(out/'discriminators.json')))
    save(out/'report.json', report)
    print(json.dumps({k:report[k] for k in ('status', 'actual_rows', 'U_ES_B_counts',
        'consistent_three_input_Boolean_gates', 'minimum_named_discriminator_states')}, sort_keys=True))


if __name__ == '__main__':
    main()
