#!/usr/bin/env python3
"""Prove a canonical boundary-carry form for the two H1487 functions.

The H1486 survivors are represented as final-CPA propagate bits in alternate
compressor layouts.  This audit removes the visual tree vocabulary: for each
final redundant pair (S,C), it proves that the surviving bit is exactly the
true product bit XOR the carry generated by adding the two lower residues
below that bit.  The pair-A/pair-B disagreement is therefore exactly a
boundary-carry disagreement, not an opcode table or operand predicate.
"""

from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path

try:
    import z3
except ImportError as error:
    raise SystemExit("z3-solver 4.15.3.0 is required") from error

from h1400_p5_representation_audit import BOOTH8
from h1486_surviving_propagate_class import EXPECTED_SIGNALS
from h1487_propagate_pair_equivalence import POSITIONS


PAIR_REPRESENTATIVES = (0, 2)
PRODUCT_TOP = 130
WIDTH = PRODUCT_TOP + 1


def digest(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def lower_residue_carry(pair, position: int):
    mask = z3.BitVecVal((1 << position) - 1, WIDTH)
    threshold = z3.BitVecVal(1 << position, WIDTH)
    low_sum = (pair[0] & mask) + (pair[1] & mask)
    return z3.If(z3.UGE(low_sum, threshold), z3.BitVecVal(1, 1), z3.BitVecVal(0, 1))


def prove_unsat(predicate, timeout_ms: int) -> dict[str, object]:
    solver = z3.SolverFor("QF_BV")
    solver.set(timeout=timeout_ms)
    solver.add(predicate)
    status = solver.check()
    result: dict[str, object] = {"status": str(status)}
    if status == z3.unknown:
        result["reason_unknown"] = solver.reason_unknown()
    return result


def csa3_truth_table() -> list[dict[str, int]]:
    rows = []
    for a in range(2):
        for b in range(2):
            for c in range(2):
                sum_bit = a ^ b ^ c
                carry_bit = (a & b) | (a & c) | (b & c)
                if a + b + c != sum_bit + 2 * carry_bit:
                    raise AssertionError("CSA3 bit identity failed")
                rows.append(
                    {
                        "a": a,
                        "b": b,
                        "c": c,
                        "sum": sum_bit,
                        "carry": carry_bit,
                    }
                )
    return rows


def booth_recode_proof() -> dict[str, object]:
    digit_formula = []
    for code, table_digit in enumerate(BOOTH8):
        bits = [(code >> bit) & 1 for bit in range(4)]
        formula_digit = bits[0] + bits[1] + 2 * bits[2] - 4 * bits[3]
        if formula_digit != table_digit:
            raise AssertionError(f"Booth formula differs at code {code}")
        digit_formula.append(formula_digit)

    coefficients = [0] * 64
    local_weights = (1, 1, 2, -4)
    for row in range(22):
        for offset, weight in enumerate(local_weights):
            source = 3 * row - 1 + offset
            if 0 <= source < 64:
                coefficients[source] += weight << (3 * row)
    expected = [1 << bit for bit in range(64)]
    if coefficients != expected:
        raise AssertionError("radix-8 recoding coefficients do not telescope")

    scaffold = sum(7 << (69 + 3 * row) for row in range(22)) + (1 << 69)
    modulus = 1 << 131
    if scaffold != 1 << 135 or scaffold % modulus:
        raise AssertionError("partial-product scaffold does not cancel")
    return {
        "all_16_booth_codes_match_linear_formula": True,
        "digit_formula_by_code": digit_formula,
        "all_64_multiplier_bit_coefficients_equal_binary_weight": True,
        "common_scaffold_exact_value": "2^135",
        "common_scaffold_mod_2^131": 0,
        "negative_row_correction": (
            "a negative row is one below 7*2^69 + digit*multiplicand; "
            "the routed +1 correction restores that exact value"
        ),
    }


def disagreement_truth_table() -> list[dict[str, int]]:
    rows = []
    for product_bit in range(2):
        for carry_a in range(2):
            for carry_b in range(2):
                selector_a = product_bit ^ carry_a
                selector_b = product_bit ^ carry_b
                if (selector_a != selector_b) != (carry_a != carry_b):
                    raise AssertionError("pair disagreement identity failed")
                rows.append(
                    {
                        "product_bit": product_bit,
                        "carry_a": carry_a,
                        "carry_b": carry_b,
                        "selector_a": selector_a,
                        "selector_b": selector_b,
                    }
                )
    return rows


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("h1486", type=Path)
    parser.add_argument("h1487", type=Path)
    parser.add_argument("output", type=Path)
    parser.add_argument("--timeout-ms", type=int, default=60_000)
    arguments = parser.parse_args()
    if arguments.output.exists():
        raise SystemExit(f"refusing to overwrite {arguments.output}")
    if z3.get_version_string() != "4.15.3":
        raise RuntimeError(f"unexpected Z3 version {z3.get_version_string()}")

    h1486 = json.loads(arguments.h1486.read_text())
    h1487 = json.loads(arguments.h1487.read_text())
    signal_order = h1486["survivor_class"]["signal_order"]
    if set(signal_order) != EXPECTED_SIGNALS:
        raise RuntimeError("H1486 signal class changed")
    if h1487["status"] != "TWO_FORMALLY_DISTINCT_SURVIVING_FUNCTIONS":
        raise RuntimeError("H1487 two-function proof is not established")

    pair_s = z3.BitVec("pair_s", WIDTH)
    pair_c = z3.BitVec("pair_c", WIDTH)
    proofs: dict[str, object] = {}
    for position in POSITIONS:
        pair = (pair_s, pair_c)
        propagate = z3.Extract(position, position, pair_s ^ pair_c)
        sum_bit = z3.Extract(position, position, pair_s + pair_c)
        carry = lower_residue_carry(pair, position)
        proofs[f"generic_boundary_identity_at_{position}"] = prove_unsat(
            propagate != sum_bit ^ carry,
            arguments.timeout_ms,
        )

    csa_truth = csa3_truth_table()
    booth_proof = booth_recode_proof()
    disagreement_truth = disagreement_truth_table()
    if any(proof["status"] != "unsat" for proof in proofs.values()):
        status = "BOUNDARY_CARRY_ISOMORPHISM_NOT_PROVED"
    else:
        status = "EXACT_BOUNDARY_CARRY_ISOMORPHISM_PROVED"

    report = {
        "experiment": "h1495_propagate_boundary_carry_isomorphism",
        "status": status,
        "hardware_execution": "none",
        "hardware_labels_opened": "none",
        "z3_version": z3.get_version_string(),
        "applicable_product_domain": {
            "multiplicand": "normalized 67-bit integer",
            "multiplier": "normalized 64-bit integer",
            "possible_cut_minus_18_columns": list(POSITIONS),
        },
        "candidate_signal_order": signal_order,
        "representatives": {
            "pair_a": signal_order[PAIR_REPRESENTATIVES[0]],
            "pair_b": signal_order[PAIR_REPRESENTATIVES[1]],
        },
        "closed_form": (
            "For final redundant words S,C and target column j: "
            "boundary_carry_j = ((S mod 2^j) + (C mod 2^j) >= 2^j); "
            "selector_j = bit_j(exact_product) XOR boundary_carry_j."
        ),
        "proofs": {
            "generic_qf_bv_lemmas": proofs,
            "csa3_all_bit_inputs": csa_truth,
            "csa42_and_tree_consequence": (
                "CSA3 preserves a+b+c modulo the word width on every bit; "
                "each CSA42 is two CSA3 applications and every four-level "
                "candidate tree therefore preserves the sum of its 24 inputs"
            ),
            "radix8_product_reconstruction": booth_proof,
            "pair_disagreement_all_boolean_inputs": disagreement_truth,
            "h1487_pair_partition": h1487["queries"],
        },
        "interpretation": {
            "confirmed": [
                "every arithmetic-exact candidate tree reconstructs the exact 67x64 product through bit 130",
                "each surviving propagate function is exactly an arithmetic lower-residue boundary carry combined with the exact product bit",
                "pair A and pair B disagree exactly when their final-CPA boundary carries disagree",
            ],
            "not_claimed": [
                "which redundant-pair construction exists in Skylake",
                "that either candidate is globally validated by hardware",
                "an R59 selector promotion",
            ],
        },
        "sha256": {
            "h1486": digest(arguments.h1486),
            "h1487": digest(arguments.h1487),
        },
        "emulator_change": "none",
        "paper_change": "none",
    }
    text = json.dumps(report, indent=2, sort_keys=True) + "\n"
    arguments.output.parent.mkdir(parents=True, exist_ok=True)
    arguments.output.write_text(text)
    print(
        json.dumps(
            {
                "output": str(arguments.output),
                "status": status,
                "proofs": {name: proof["status"] for name, proof in proofs.items()},
                "report_sha256": hashlib.sha256(text.encode()).hexdigest(),
            },
            sort_keys=True,
        )
    )


if __name__ == "__main__":
    main()
