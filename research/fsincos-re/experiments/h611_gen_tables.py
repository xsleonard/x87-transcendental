#!/usr/bin/env python3
"""h611: generate src/fsincos_r57_tables.h from the merged
Round-57 model (h609 semantics: h604_model_v3 overridden by
h606_v5_model on its ten stratum-sides).

Key packing (uint32):
  bits 0-1   dist - 7            (dist 7..10)
  bits 2-4   low3                (1..7)
  bit  5     ce == -73
  bit  6     side == 'dn'
  bits 7-10  xd12                (0..11)
  bit  11    is_v5 (zone carries mf16)
  bits 12-15 mf16                (0..15; 0 for v3 zones)
  bits 16-21 st (offset entries only; 0..63)
Zone values (q, a, b) are emitted as C99 hex-float literals
(exact doubles).  Both arrays sorted by key for bsearch.
"""
from h609_ref_predictor import load_model


def pack(key, xd12, mf16, is_v5, st=0):
    dist, low3, ce, side = key
    assert 7 <= dist <= 10 and 1 <= low3 <= 7
    assert ce in (-72, -73) and side in ("up", "dn")
    v = ((dist - 7) | (low3 << 2) | ((ce == -73) << 5)
         | ((side == "dn") << 6) | (xd12 << 7)
         | (is_v5 << 11) | (mf16 << 12) | (st << 16))
    return v


def main():
    fits, cbest = load_model()
    zones = []
    for zid, (q, a, b) in fits.items():
        if len(zid) == 3:
            key, xd12, mf16 = zid
            zones.append((pack(key, xd12, mf16, 1), q, a, b))
        else:
            key, xd12 = zid
            zones.append((pack(key, xd12, 0, 0), q, a, b))
    zones.sort()
    offs = []
    for (zid, st), c in cbest.items():
        if c == 0:
            continue
        if len(zid) == 3:
            key, xd12, mf16 = zid
            offs.append((pack(key, xd12, mf16, 1, st), c))
        else:
            key, xd12 = zid
            offs.append((pack(key, xd12, 0, 0, st), c))
    offs.sort()
    assert len({k for k, *_ in zones}) == len(zones)
    assert len({k for k, _ in offs}) == len(offs)
    out = ["/* Generated by experiments/h611_gen_tables.py from",
           " * h604_model_v3.json + h606_v5_model.json (Round-57",
           " * borrow-rule zone tables).  Do not edit by hand. */",
           f"#define R57_N_ZONES {len(zones)}",
           f"#define R57_N_OFFS {len(offs)}",
           "static const uint32_t r57_zone_keys[R57_N_ZONES] = {"]
    line = []
    for k, q, a, b in zones:
        line.append(f"0x{k:05x}u,")
        if len(line) == 8:
            out.append("    " + " ".join(line))
            line = []
    if line:
        out.append("    " + " ".join(line))
    out.append("};")
    out.append("static const double r57_zone_qab"
               "[R57_N_ZONES][3] = {")
    for k, q, a, b in zones:
        out.append(f"    {{ {float(q).hex()}, {float(a).hex()},"
                   f" {float(b).hex()} }},")
    out.append("};")
    out.append("static const uint32_t r57_off_keys"
               "[R57_N_OFFS] = {")
    line = []
    for k, c in offs:
        line.append(f"0x{k:06x}u,")
        if len(line) == 8:
            out.append("    " + " ".join(line))
            line = []
    if line:
        out.append("    " + " ".join(line))
    out.append("};")
    out.append("static const int8_t r57_off_c[R57_N_OFFS] = {")
    line = []
    for k, c in offs:
        line.append(f"{c},")
        if len(line) == 16:
            out.append("    " + " ".join(line))
            line = []
    if line:
        out.append("    " + " ".join(line))
    out.append("};")
    path = ("/Users/steve/llm/x87-transcendental/fsincos-re/"
            "src/fsincos_r57_tables.h")
    open(path, "w").write("\n".join(out) + "\n")
    print(f"{len(zones)} zones, {len(offs)} nonzero offsets "
          f"-> {path}")


if __name__ == "__main__":
    main()
