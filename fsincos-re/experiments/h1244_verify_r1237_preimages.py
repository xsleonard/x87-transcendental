#!/usr/bin/env python3
"""Independently verify the frozen R1237 preimage bank.

The frozen manifest is generated by a compact C evaluator.  This pass uses
the independent Python exact-integer schedule plus the full model's internal
dump to verify every boundary coordinate and CPA selection bit.  It also
records whether enabling R1237 changes an architectural result; no hardware
instruction or hardware label participates.
"""

from __future__ import annotations

import argparse
import csv
import hashlib
from collections import Counter
from pathlib import Path

from h1210_stagea_residual_reframe import parse_dump, run
from h1241_r1237_adversarial_bank import event_for
from h1184_upstream_halfway_audit import schedule


MODES = ("rn", "rd", "ru", "rz")


def digest(path: Path) -> str:
    value = hashlib.sha256()
    with path.open("rb") as source:
        for block in iter(lambda: source.read(1 << 20), b""):
            value.update(block)
    return value.hexdigest()


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("baseline", type=Path)
    parser.add_argument("candidate", type=Path)
    parser.add_argument("manifest", type=Path)
    parser.add_argument("report", type=Path)
    args = parser.parse_args()
    changes_path = args.report.with_name(args.report.stem + "_changes.tsv")
    for path in (args.report, changes_path):
        if path.exists():
            raise SystemExit(f"refusing to overwrite {path}")

    with args.manifest.open(newline="") as source:
        manifest = list(csv.DictReader(source, delimiter="\t"))
    operands = sorted({row["op"] for row in manifest})
    if len(operands) != len(manifest):
        raise RuntimeError("expected one selected event per operand")

    _, stderr = run(args.baseline, "rn", operands, dump=True)
    dumped = {row["op"]: row for row in parse_dump(stderr, operands)}
    counts = Counter()
    diagnostics = []
    compared_fields = {
        "q": "q",
        "retained_lsb": "retained_lsb",
        "increments": "increments",
        "product_bit65": "selected_bit65",
        "r1237_fires": "fires",
    }
    for frozen in manifest:
        chain = frozen["chain"]
        computed = event_for(schedule(dumped[frozen["op"]]), chain)
        expected_stage = f"{chain}.add2"
        if computed["stage"] != expected_stage:
            raise RuntimeError(
                f"stage mismatch {frozen['op']}: {computed['stage']}")
        row_mismatches = []
        for frozen_name, computed_name in compared_fields.items():
            if int(frozen[frozen_name]) != int(computed[computed_name]):
                row_mismatches.append(
                    f"{frozen_name}={frozen[frozen_name]}/"
                    f"{computed[computed_name]}")
        counts[f"q.{int(frozen['q']):+d}"] += 1
        counts[f"sum0_bit65.{computed['sum0_bit65']}"] += 1
        counts[f"selected_bit65.{computed['selected_bit65']}"] += 1
        counts[f"incoming_carry.{computed['incoming_carry']}"] += 1
        counts[f"cpa_mux_changes_bit.{int(computed['sum0_bit65'] != computed['selected_bit65'])}"] += 1
        counts[f"verification_match.{int(not row_mismatches)}"] += 1
        if row_mismatches:
            diagnostics.append((
                frozen["op"], chain, ",".join(row_mismatches)))

    architectural_changes = []
    for mode in MODES:
        baseline_values, _ = run(args.baseline, mode, operands)
        candidate_values, _ = run(args.candidate, mode, operands)
        for operand, baseline, candidate in zip(
                operands, baseline_values, candidate_values):
            changed = baseline != candidate
            counts[f"mode.{mode}.changed.{int(changed)}"] += 1
            if changed:
                architectural_changes.append((
                    mode, operand, baseline, candidate))

    args.report.parent.mkdir(parents=True, exist_ok=True)
    with changes_path.open("x", newline="") as target:
        writer = csv.writer(target, delimiter="\t")
        writer.writerow(("mode", "op", "baseline", "candidate"))
        writer.writerows(architectural_changes)
    with args.report.open("x") as target:
        target.write(f"baseline_sha256\t{digest(args.baseline)}\n")
        target.write(f"candidate_sha256\t{digest(args.candidate)}\n")
        target.write(f"manifest_sha256\t{digest(args.manifest)}\n")
        target.write("hardware_policy\tsoftware_only_no_x87_no_labels\n")
        target.write(f"events\t{len(manifest)}\n")
        target.write(f"operands\t{len(operands)}\n")
        target.write(f"verification_mismatches\t{len(diagnostics)}\n")
        target.write(f"architectural_changes\t{len(architectural_changes)}\n")
        target.write(f"changes_sha256\t{digest(changes_path)}\n")
        target.write("\n[counts]\n")
        for name, value in sorted(counts.items()):
            target.write(f"{name}\t{value}\n")
        target.write("\n[mismatches]\n")
        target.write("op\tchain\tdetail\n")
        for diagnostic in diagnostics:
            target.write("\t".join(diagnostic) + "\n")

    print(
        f"wrote {args.report} events={len(manifest)} "
        f"mismatches={len(diagnostics)} "
        f"architectural_changes={len(architectural_changes)}", flush=True)


if __name__ == "__main__":
    main()
