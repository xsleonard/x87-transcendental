#!/usr/bin/env python3
"""Refine R1266 on every cached leg whose output it changes.

R1266's two-wire producer gate fixes the final two R1263 residual legs but
also changes hundreds of previously exact cached legs.  Because the R1266
gate is true on every row in this file, an exact literal here would be the
missing third condition; an exact two-literal conjunction would identify two
additional conditions.  Intermediate state is regenerated by the software
baseline.  Hardware is never executed.
"""

from __future__ import annotations

import argparse
import csv
import hashlib
from collections import defaultdict
from pathlib import Path

from h1210_stagea_residual_reframe import parse_dump, run
from h1257_terminal_two_wire_gates import banked, representative


def digest(path: Path) -> str:
    value = hashlib.sha256()
    with path.open("rb") as source:
        for block in iter(lambda: source.read(1 << 20), b""):
            value.update(block)
    return value.hexdigest()


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("changes", type=Path)
    parser.add_argument("baseline", type=Path)
    parser.add_argument("report", type=Path)
    args = parser.parse_args()
    if args.report.exists():
        raise SystemExit(f"refusing to overwrite {args.report}")

    labeled: dict[str, list[tuple[str, str]]] = defaultdict(list)
    with args.changes.open(newline="") as source:
        for row in csv.DictReader(source, delimiter="\t"):
            classification = row["classification"]
            if classification not in ("fix", "regression"):
                raise RuntimeError("unexpected classification: " + classification)
            labeled[row["mode"].lower()].append((
                row["op"].lower(),
                "POS" if classification == "fix" else "NEG",
            ))

    rows = []
    for mode in sorted(labeled):
        items = labeled[mode]
        operands = [operand for operand, _ in items]
        _, stderr = run(args.baseline, mode, operands, dump=True)
        records = parse_dump(stderr, operands)
        for record, (_, label) in zip(records, items):
            record["mode"] = mode
            record["label"] = label
            rows.append(record)

    columns: dict[str, int] = defaultdict(int)
    truth = 0
    schema = set()
    for index, row in enumerate(rows):
        features = banked(row)
        schema.update(features)
        for name, value in features.items():
            columns[name] |= int(bool(value)) << index
        truth |= int(row["label"] == "POS") << index
        if (index + 1) % 50 == 0:
            print(f"features {index + 1}/{len(rows)}", flush=True)
    for name in schema:
        columns[name] |= 0

    all_mask = (1 << len(rows)) - 1
    patterns: dict[int, list[str]] = defaultdict(list)
    for name, pattern in columns.items():
        patterns[pattern].append(name)
    literals: dict[int, list[str]] = defaultdict(list)
    for pattern, names in patterns.items():
        for name in names:
            literals[pattern].append(name)
            literals[pattern ^ all_mask].append("!" + name)
    literal_patterns = sorted(literals)

    supersets = [pattern for pattern in literal_patterns
                 if pattern & truth == truth]
    exact_singles = sorted(
        literals.get(truth, []), key=lambda name: (len(name), name))
    near_singles = sorted(
        ((pattern.bit_count() - truth.bit_count(),
          representative(literals[pattern]), len(literals[pattern]))
         for pattern in supersets),
        key=lambda item: (item[0], len(item[1]), item[1]),
    )

    exact_ands = []
    for left_index, left_pattern in enumerate(supersets):
        for right_pattern in supersets[left_index:]:
            if left_pattern & right_pattern != truth:
                continue
            left = representative(literals[left_pattern])
            right = representative(literals[right_pattern])
            left_bank = left.lstrip("!").split(".", 1)[0]
            right_bank = right.lstrip("!").split(".", 1)[0]
            false_positive_balance = min(
                left_pattern.bit_count() - truth.bit_count(),
                right_pattern.bit_count() - truth.bit_count(),
            )
            exact_ands.append((
                -int(left_bank != right_bank), -false_positive_balance,
                len(left) + len(right), left, right,
                len(literals[left_pattern]), len(literals[right_pattern]),
            ))
    exact_ands.sort()

    args.report.parent.mkdir(parents=True, exist_ok=True)
    with args.report.open("x") as target:
        target.write(f"changes_sha256\t{digest(args.changes)}\n")
        target.write(f"baseline_sha256\t{digest(args.baseline)}\n")
        target.write(f"rows\t{len(rows)}\n")
        target.write(f"targets\t{truth.bit_count()}\n")
        target.write(f"features\t{len(columns)}\n")
        target.write(f"wire_patterns\t{len(patterns)}\n")
        target.write(f"literal_patterns\t{len(literal_patterns)}\n")
        target.write(f"target_superset_literals\t{len(supersets)}\n")
        target.write(f"exact_single_literals\t{len(exact_singles)}\n")
        target.write(f"exact_two_literal_ands\t{len(exact_ands)}\n")
        target.write("hardware_policy\tcached_labels_only_no_x87_execution\n")
        target.write("\n[rows]\n")
        target.write("label\tmode\top\ttheta\tlow3\trsh\tb1\tb2\tbranch\n")
        for row in rows:
            target.write("\t".join(
                row.get(name, "") for name in
                ("label", "mode", "op", "theta", "low3", "rsh",
                 "b1", "b2", "branch")
            ) + "\n")
        target.write("\n[exact single literals]\n")
        for name in exact_singles:
            target.write(name + "\n")
        target.write("\n[closest target-superset literals]\n")
        target.write("false_positives\tliteral\tequivalents\n")
        for false_positives, name, equivalents in near_singles[:500]:
            target.write(f"{false_positives}\t{name}\t{equivalents}\n")
        target.write("\n[exact two-literal conjunctions]\n")
        target.write(
            "cross_bank\tbalance\tleft\tright\t"
            "left_equivalents\tright_equivalents\n")
        for (negative_cross, negative_balance, _, left, right,
             left_count, right_count) in exact_ands[:5000]:
            target.write("\t".join(map(str, (
                -negative_cross, -negative_balance, left, right,
                left_count, right_count,
            ))) + "\n")

    print(
        f"wrote {args.report} rows={len(rows)} features={len(columns)} "
        f"singles={len(exact_singles)} exact_ands={len(exact_ands)}",
        flush=True,
    )


if __name__ == "__main__":
    main()
