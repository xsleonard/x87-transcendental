#!/usr/bin/env python3
"""Search a complete cached equality-resolver set for structural gates.

R1259 found that the four post-R1237 equality misses share one named P5
multiplier-tree wire, but the complete 56M-leg wall exposed six additional
operands on which that wire makes the equality decision worse.  This audit
joins those wall counterexamples to every constraining equality row in the
dense target-cell corpus and searches the same fixed circuit/history banks
for single wires and complete two-input Boolean gates.

The wall changes file supplies only cached classifications and operand names.
Intermediate state for its regression operands is regenerated by the
software model; no x87 instruction or new hardware capture is performed.
"""

from __future__ import annotations

import argparse
import csv
import gzip
import hashlib
from collections import defaultdict
from pathlib import Path

from h1210_stagea_residual_reframe import parse_dump, run
from h1257_terminal_two_wire_gates import banked, representative


def digest(path: Path) -> str:
    value = hashlib.sha256()
    with path.open("rb") as source:
        for block in iter(lambda: source.read(1 << 20), b""):
            value.update(block)
    return value.hexdigest()


def is_equality(row: dict[str, str]) -> bool:
    rd3 = int(row["rd3"], 16)
    shift = int(row["rsh"])
    return rd3 == 1 << shift or rd3 == 1 << (shift + 1)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("dense_features", type=Path)
    parser.add_argument("dense_labels", type=Path)
    parser.add_argument("wall_changes", type=Path)
    parser.add_argument("model", type=Path)
    parser.add_argument("report", type=Path)
    args = parser.parse_args()
    if args.report.exists():
        raise SystemExit(f"refusing to overwrite {args.report}")

    with args.dense_labels.open(newline="") as source:
        labels = {
            (row["corpus"], row["index"]): row
            for row in csv.DictReader(source, delimiter="\t")
            if row["selector_status"] == "constraining"
        }

    rows = []
    with gzip.open(args.dense_features, "rt", newline="") as source:
        for row in csv.DictReader(source, delimiter="\t"):
            label = labels.get((row["corpus"], row["index"]))
            if label is None or not is_equality(row):
                continue
            row["label"] = "POS" if label["target_flip"] == "1" else "NEG"
            rows.append(row)

    regression_operands = []
    with args.wall_changes.open(newline="") as source:
        for row in csv.DictReader(source, delimiter="\t"):
            operand = row["op"].lower()
            if (row["classification"] == "regression"
                    and operand not in regression_operands):
                regression_operands.append(operand)
    _, stderr = run(str(args.model), "rn", regression_operands, dump=True)
    for row in parse_dump(stderr, regression_operands):
        if not is_equality(row):
            raise RuntimeError("wall regression was not an equality: "
                               + row["op"])
        row["label"] = "NEG"
        rows.append(row)

    feature_rows = []
    schema = set()
    truth = 0
    for index, row in enumerate(rows):
        features = banked(row)
        feature_rows.append(features)
        schema.update(features)
        truth |= int(row["label"] == "POS") << index

    columns: dict[str, int] = defaultdict(int)
    for index, features in enumerate(feature_rows):
        for name, value in features.items():
            columns[name] |= int(bool(value)) << index
    for name in schema:
        columns[name] |= 0

    all_mask = (1 << len(rows)) - 1
    patterns: dict[int, list[str]] = defaultdict(list)
    for name, pattern in columns.items():
        patterns[pattern].append(name)
    literals: dict[int, list[str]] = defaultdict(list)
    for pattern, names in patterns.items():
        for name in names:
            literals[pattern].append(name)
            literals[pattern ^ all_mask].append("!" + name)
    literal_patterns = sorted(literals)

    singles = []
    for pattern in literal_patterns:
        if pattern == truth:
            singles.extend(literals[pattern])

    matches = set()
    supersets = [p for p in literal_patterns if p & truth == truth]
    subsets = [p for p in literal_patterns if p & ~truth & all_mask == 0]
    for left_index, left in enumerate(supersets):
        for right in supersets[left_index:]:
            if left & right == truth:
                matches.add(("and", left, right))
    for left_index, left in enumerate(subsets):
        for right in subsets[left_index:]:
            if left | right == truth:
                matches.add(("or", left, right))
    literal_set = set(literal_patterns)
    for left in literal_patterns:
        right = left ^ truth
        if right in literal_set and left <= right:
            matches.add(("xor", left, right))

    ranked = []
    for gate, left_pattern, right_pattern in matches:
        left = representative(literals[left_pattern])
        right = representative(literals[right_pattern])
        left_bank = left.lstrip("!").split(".", 1)[0]
        right_bank = right.lstrip("!").split(".", 1)[0]
        cross_bank = int(left_bank != right_bank)
        balance = min(
            left_pattern.bit_count(), len(rows) - left_pattern.bit_count(),
            right_pattern.bit_count(), len(rows) - right_pattern.bit_count(),
        )
        ranked.append((
            -cross_bank, -balance, len(left) + len(right), gate, left, right,
            len(literals[left_pattern]), len(literals[right_pattern]),
        ))
    ranked.sort()

    args.report.parent.mkdir(parents=True, exist_ok=True)
    with args.report.open("x") as target:
        target.write(f"dense_features_sha256\t{digest(args.dense_features)}\n")
        target.write(f"dense_labels_sha256\t{digest(args.dense_labels)}\n")
        target.write(f"wall_changes_sha256\t{digest(args.wall_changes)}\n")
        target.write(f"model_sha256\t{digest(args.model)}\n")
        target.write(f"rows\t{len(rows)}\n")
        target.write(f"targets\t{truth.bit_count()}\n")
        target.write(f"wall_regression_operands\t{len(regression_operands)}\n")
        target.write(f"features\t{len(columns)}\n")
        target.write(f"wire_patterns\t{len(patterns)}\n")
        target.write(f"literal_patterns\t{len(literal_patterns)}\n")
        target.write(f"exact_single_literals\t{len(singles)}\n")
        target.write(f"exact_two_wire_gates\t{len(ranked)}\n")
        target.write("hardware_policy\tcached_labels_only_no_x87_execution\n")
        target.write("\n[rows]\n")
        target.write("label\top\ttheta\tlow3\trsh\tb1\tb2\n")
        for row in rows:
            target.write("\t".join(
                row[name] for name in
                ("label", "op", "theta", "low3", "rsh", "b1", "b2")
            ) + "\n")
        target.write("\n[exact single literals]\n")
        for name in sorted(singles, key=lambda value: (len(value), value)):
            target.write(name + "\n")
        target.write("\n[exact two-wire gates]\n")
        target.write(
            "cross_bank\tbalance\tgate\tleft\tright\t"
            "left_equivalents\tright_equivalents\n"
        )
        for (negative_cross, negative_balance, _, gate, left, right,
             left_count, right_count) in ranked[:5000]:
            target.write("\t".join(map(str, (
                -negative_cross, -negative_balance, gate, left, right,
                left_count, right_count,
            ))) + "\n")

    print(
        f"wrote {args.report} rows={len(rows)} features={len(columns)} "
        f"singles={len(singles)} exact_gates={len(ranked)}",
        flush=True,
    )


if __name__ == "__main__":
    main()
